"""Generate PBS Pro job scripts (one per run spec) and a submit.sh for the CCAST cluster."""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path
from string import Template

from cua.experiments.specs import budget_specs, part_a_specs, proxy_specs
from cua.train import TrainConfig

DEFAULT_PROJECT = "/mmfs1/scratch/solomon.owusu.1/road_damage_augmentation_research"
_TEMPLATE = Path(__file__).with_name("job_template.pbs")
# CUDA hidden: the gate tests assume the CPU trainer (exact equality, no AMP step skips).
_PYTEST_BLOCK = '''CUDA_VISIBLE_DEVICES= pytest -q -x -m "not slow" tests/cua || exit $?
'''
_MARGIN_S = 20 * 60
_SMOKE_WALLTIME_S = 3600
_SMOKE_MAX_IMAGES = 64


def _walltime_seconds(spec: TrainConfig, smoke: bool) -> int:
    if smoke:
        return _SMOKE_WALLTIME_S
    return 6 * 3600 if spec.run_id.startswith("A-") else 24 * 3600


def _hms(seconds: int) -> str:
    return f"{seconds // 3600:02d}:{seconds % 3600 // 60:02d}:{seconds % 60:02d}"


def _job_name(run_id: str) -> str:
    return "cua" + hashlib.sha1(run_id.encode("utf-8")).hexdigest()[:8]


def _write(path: Path, text: str) -> None:
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write(text)


def make_jobs(specs: list[TrainConfig], out_dir: Path, project: str = DEFAULT_PROJECT,
              smoke: bool = False) -> Path:
    """Write one <run_id>.pbs per spec plus submit.sh into out_dir; return the submit.sh path.

    All specs must share one (dataset, detector) pair. Non-arm jobs (init_run is None) are submitted first;
    each arm is submitted with -W depend=afterok on the warm job of its seed.
    """
    if not specs:
        raise ValueError("No specs given")
    pairs = {(s.dataset, s.detector) for s in specs}
    if len(pairs) != 1:
        raise ValueError(f"make_jobs needs a single (dataset, detector) pair, got {sorted(pairs)}")
    out_dir = Path(out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    mode = "smoke" if smoke else "real"
    marker = out_dir / ".mode"
    if marker.exists():
        existing = marker.read_text(encoding="utf-8").strip()
    else:
        existing = mode if not any(out_dir.glob("*.pbs")) else None
    if existing is not None and existing != mode:
        raise ValueError(f"{out_dir} already holds {existing} jobs; use a different --out for {mode} jobs")
    if existing is None:
        raise ValueError(f"{out_dir} holds .pbs files of unknown mode; use an empty --out")
    _write(marker, mode + "\n")
    template = Template(_TEMPLATE.read_text(encoding="utf-8"))
    project = project.rstrip("/")
    runs_root = f"{project}/{'cua_runs_smoke' if smoke else 'cua_runs'}"
    data_root = f"{project}/cua_data"

    for s in specs:
        wall = _walltime_seconds(s, smoke)
        pbs_path = out_dir / f"{s.run_id}.pbs"
        text = template.substitute(
            run_id=s.run_id, job_name=_job_name(s.run_id), walltime=_hms(wall),
            deadline=wall - _MARGIN_S, project=project, runs_root=runs_root, data_root=data_root,
            pbs_path=pbs_path.as_posix(),
            pytest_block=_PYTEST_BLOCK if s.init_run is None else "",
            smoke_args=f" --max-train-images {_SMOKE_MAX_IMAGES}" if smoke else "")
        _write(pbs_path, text)

    lines = ["#!/bin/bash",
             "# Generated by cua.ccast.make_jobs. Run from any directory on the CCAST login node.",
             "set -euo pipefail",
             f'mkdir -p "{runs_root}/_logs"',
             f'cd "{out_dir.as_posix()}"', ""]
    warm_vars: dict[str, str] = {}
    for s in specs:
        if s.init_run is None:
            lines.append(f"# {s.run_id}")
            if s.run_id.endswith("-warm"):
                var = f"WARM_s{s.seed}"
                warm_vars[s.run_id] = var
                lines.append(f"{var}=$(qsub {s.run_id}.pbs)")
                lines.append(f'echo "{s.run_id}: ${var}"')
            else:
                lines.append(f"qsub {s.run_id}.pbs")
    arms = [s for s in specs if s.init_run is not None]
    if arms:
        lines.append("")
    for s in arms:
        if s.init_run not in warm_vars:
            raise ValueError(f"{s.run_id}: warm run {s.init_run!r} is not in the spec list")
        lines.append(f"qsub -W depend=afterok:${warm_vars[s.init_run]} {s.run_id}.pbs")
    _write(out_dir / "submit.sh", "\n".join(lines) + "\n")
    return out_dir / "submit.sh"


def _csv(text: str) -> list[str]:
    return [t for t in text.split(",") if t]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="cua.ccast.make_jobs")
    ap.add_argument("--family", required=True, choices=("budget", "part_a", "proxy"))
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--detector", required=True)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--epochs", type=int, default=None)
    ap.add_argument("--edits", default="")
    ap.add_argument("--seeds", default="0,1,2")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--project", default=DEFAULT_PROJECT)
    a = ap.parse_args(argv)
    try:
        if a.family == "budget":
            specs = budget_specs(a.dataset, a.detector, a.epochs)
        elif a.family == "part_a":
            specs = part_a_specs(a.dataset, a.detector, tuple(int(x) for x in _csv(a.seeds)))
        else:
            if (a.dataset, a.detector) != ("rdd", "fasterrcnn"):
                ap.error("the proxy family is fixed to --dataset rdd --detector fasterrcnn")
            if a.epochs is None:
                ap.error("--epochs is required for the proxy family")
            specs = proxy_specs(_csv(a.edits), a.epochs)
        for label, value in (("--out", a.out.resolve().as_posix()), ("--project", a.project)):
            if not value.startswith("/"):
                print(f"warning: {label} {value!r} is not a POSIX absolute path; these jobs must be generated "
                      f"on the cluster to be submittable", file=sys.stderr)
        submit = make_jobs(specs, a.out, project=a.project, smoke=a.smoke)
    except ValueError as e:
        ap.error(str(e))
    print(f"wrote {len(specs)} job scripts and {submit}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
