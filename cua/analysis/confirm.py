"""Confirmation of the three strength-pilot picks on fresh seeds (reports/cua_confirm/PROTOCOL.md).

For each pick (edit, level, class c) and seed k in CONFIRM_SEEDS, from the final-epoch validation per-class AP50:
  d_k = AP50(c | S-...-s<k>-<edit>-x<level>) - AP50(c | A-...-s<k>-base)          (the pick helps its class)
  s_k = d_k - mean over the other classes of the same arm-minus-base delta          (and more than the others)
Each statistic gets a one-sided paired t-test over seeds (H1: mean > 0). A pick is confirmed when both
Holm-adjusted p-values (Holm over the three picks, separately per statistic) are below CONFIRM_ALPHA.

    python -m cua.analysis.confirm --runs-root <cua_runs> --out <dir>
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

from cua.analysis.part_a import _final_rows
from cua.experiments.specs import CONFIRM_PICKS, CONFIRM_SEEDS

CONFIRM_ALPHA = 0.05


def one_sided(x) -> dict:
    x = np.asarray(list(x), dtype=np.float64)
    n = len(x)
    if n < 2:
        return {"mean": float(x.mean()) if n else None, "t": None, "p": None, "lo": None, "hi": None, "n": n}
    sd = float(x.std(ddof=1))
    se = sd / math.sqrt(n)
    t = float(x.mean() / se) if se > 0 else (math.inf if x.mean() > 0 else -math.inf)
    half = float(stats.t.ppf(0.975, n - 1) * se)
    return {"mean": float(x.mean()), "t": t, "p": float(stats.t.sf(t, n - 1)),
            "lo": float(x.mean()) - half, "hi": float(x.mean()) + half, "n": n}


def holm(ps: list[float | None]) -> list[float | None]:
    idx = [i for i, p in enumerate(ps) if p is not None]
    order = sorted(idx, key=lambda i: ps[i])
    out: list[float | None] = [None] * len(ps)
    running = 0.0
    for r, i in enumerate(order):
        running = max(running, min(1.0, (len(order) - r) * ps[i]))
        out[i] = running
    return out


def pick_deltas(runs_root: Path, edit: str, level: int, cls: str, seeds=CONFIRM_SEEDS) -> tuple[list, list, list]:
    """(per-seed target deltas d_k, per-seed specificity s_k, missing run ids)."""
    d, s, missing = [], [], []
    for k in seeds:
        base = Path(runs_root) / f"A-dacl10k-fasterrcnn-s{k}-base"
        arm = Path(runs_root) / f"S-dacl10k-fasterrcnn-s{k}-{edit}-x{level}"
        gone = [r.name for r in (base, arm) if not (r / "COMPLETE.json").exists()]
        if gone:
            missing += gone
            continue
        b, a = dict(_final_rows(base)), dict(_final_rows(arm))
        if cls not in a or cls not in b:
            raise ValueError(f"class {cls!r} missing in {arm.name} or {base.name}")
        delta = {c: a[c] - b[c] for c in a if c in b}
        others = [v for c, v in delta.items() if c != cls]
        d.append(delta[cls])
        s.append(delta[cls] - float(np.mean(others)))
    return d, s, missing


def summarize(runs_root: Path, picks=CONFIRM_PICKS, seeds=CONFIRM_SEEDS) -> dict:
    rows, missing = [], []
    for e, lv, c in picks:
        d, s, m = pick_deltas(runs_root, e, lv, c, seeds)
        missing += m
        rows.append({"edit": e, "level": lv, "class": c, "d": d, "s": s,
                     "target": one_sided(d), "specific": one_sided(s)})
    for key in ("target", "specific"):
        for r, p in zip(rows, holm([r[key]["p"] for r in rows])):
            r[key]["p_holm"] = p
    for r in rows:
        r["confirmed"] = bool(len(r["d"]) == len(seeds)
                              and r["target"]["p_holm"] is not None and r["target"]["p_holm"] < CONFIRM_ALPHA
                              and r["specific"]["p_holm"] is not None and r["specific"]["p_holm"] < CONFIRM_ALPHA)
    return {"picks": rows, "missing_runs": sorted(set(missing)), "alpha": CONFIRM_ALPHA, "seeds": list(seeds)}


def write_report(res: dict, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "confirm.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    f = lambda x, d=2: "n/a" if x is None else f"{x:+.{d}f}"  # noqa: E731
    g = lambda x: "n/a" if x is None else f"{x:.3g}"  # noqa: E731
    lines = ["# Confirmation of the strength-pilot picks (fresh seeds " + ", ".join(map(str, res["seeds"])) + ")", "",
             "Protocol: `reports/cua_confirm/PROTOCOL.md`. Generated by `cua/analysis/confirm.py`.", ""]
    if res["missing_runs"]:
        lines += [f"**Incomplete: {len(res['missing_runs'])} run(s) missing:** " + ", ".join(res["missing_runs"]), ""]
    lines += ["| Pick | Target Δ per seed | Mean [95% t] | p (Holm) | Δ − other classes | Mean [95% t] | p (Holm) | Confirmed |",
              "|---|---|---|---|---|---|---|---|"]
    for r in res["picks"]:
        t, s = r["target"], r["specific"]
        lines.append(f"| {r['class']} ← {r['edit']}@x{r['level']} | {', '.join(f(x) for x in r['d'])} | "
                     f"{f(t['mean'])} [{f(t['lo'])}, {f(t['hi'])}] | {g(t['p_holm'])} | "
                     f"{', '.join(f(x) for x in r['s'])} | {f(s['mean'])} [{f(s['lo'])}, {f(s['hi'])}] | "
                     f"{g(s['p_holm'])} | {'yes' if r['confirmed'] else 'no'} |")
    (out / "CONFIRM.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="cua.analysis.confirm")
    ap.add_argument("--runs-root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    res = summarize(a.runs_root)
    write_report(res, a.out)
    print(f"wrote {a.out / 'CONFIRM.md'}; confirmed: {[r['class'] for r in res['picks'] if r['confirmed']]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
